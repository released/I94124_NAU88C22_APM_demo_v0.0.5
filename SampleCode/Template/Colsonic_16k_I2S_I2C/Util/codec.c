void I2C_Master_Write_Handler(I2C_T* i2c)
{
    if(I2C_GET_TIMEOUT_FLAG(i2c))
        I2C_ClearTimeoutFlag(i2c);
    else
    {
        switch(I2C_GET_STATUS(i2c))
        {
        // START has been transmitted and Write SLA+W to Register I2CDAT.
        case 0x08:
			I2C_SET_DATA(i2c, s_MIC_I2CCtrl.u8DeviceAddr << 1);
            I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
            break;
        // SLA+W has been transmitted and ACK has been received.
        case 0x18:
            I2C_SET_DATA(i2c, s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter++]);
            I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
            break;
        // SLA+W has been transmitted and NACK has been received.
        case 0x20:
            I2C_STOP(i2c);
            I2C_START(i2c);
            s_MIC_I2CCtrl.u16WriteSize = 0;
            break;
        // DATA has been transmitted and ACK has been received.
        case 0x28:
            if(s_MIC_I2CCtrl.u16Counter < s_MIC_I2CCtrl.u16WriteSize)
            {
                I2C_SET_DATA(i2c, s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter++]);
                I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
            }
            else
            {
				I2C_SET_CONTROL_REG(i2c, I2C_CTL_STO_SI);
				// transfer complete
				s_MIC_I2CCtrl.u16WriteSize = 0;	
            }
            break;
		case 0x30:
			I2C_SET_DATA(i2c, s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter-1]);
            I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
			break;
		case 0x38:
			s_MIC_I2CCtrl.u16Counter = 0;
			I2C_START(i2c);
			break; 
		}		
    }	
}

void I2C_Master_Read_Handler(I2C_T* i2c)
{
    if(I2C_GET_TIMEOUT_FLAG(i2c))
        I2C_ClearTimeoutFlag(i2c);
    else
    {
        switch(I2C_GET_STATUS(i2c))
        {
        // START has been transmitted and Write SLA+W to Register I2CDAT.
        case 0x08:
			if(s_MIC_I2CCtrl.u16WriteSize == 0)
			{
				I2C_SET_DATA(i2c, (s_MIC_I2CCtrl.u8DeviceAddr << 1) | 0x1);
			}
			else
				I2C_SET_DATA(i2c, s_MIC_I2CCtrl.u8DeviceAddr << 1);
            I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
            break;
        // SLA+W has been transmitted and ACK has been received.
        case 0x18:
            I2C_SET_DATA(i2c, s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter++]);
            I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
            break;
        // SLA+W has been transmitted and NACK has been received.
        case 0x20:
            I2C_STOP(i2c);
            I2C_START(i2c);
            s_MIC_I2CCtrl.u16WriteSize = 0;
            break;
        // DATA has been transmitted and ACK has been received.
        case 0x28:
            if(s_MIC_I2CCtrl.u16Counter < s_MIC_I2CCtrl.u16WriteSize)
            {
                I2C_SET_DATA(i2c, s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter++]);
                I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
            }
            else
            {
				s_MIC_I2CCtrl.u16Counter = 0;
				s_MIC_I2CCtrl.u16WriteSize = 0;	
				I2C_SET_CONTROL_REG(i2c, (I2C_CTL_STO | I2C_CTL_SI | I2C_CTL_STA));		
            }
            break;
		case 0x30:
			I2C_SET_DATA(i2c, s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter-1]);
            I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
			break;
		case 0x38:
			s_MIC_I2CCtrl.u16Counter = 0;
			I2C_START(i2c);
			break; 
		
		// Master Read
		case 0x40:  // SLA+R has been transmitted and ACK has been received 
			if(s_MIC_I2CCtrl.u16ReadSize <= 1)
				// NACK for end of read
                I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
			else
				I2C_SET_CONTROL_REG(i2c, (I2C_CTL_SI|I2C_CTL_AA));
			break;
		
		case 0x48:  // SLA+R has been transmitted and NACK has been received
			// Stop I2C and start again
			I2C_SET_CONTROL_REG(i2c, (I2C_CTL_STO | I2C_CTL_SI | I2C_CTL_STA));
			break;
		
		case 0x50:  // DATA has been received and ACK has been returned		
			s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter++] = I2C_GET_DATA(i2c);
			if(s_MIC_I2CCtrl.u16Counter < s_MIC_I2CCtrl.u16ReadSize-1)
			{
				I2C_SET_CONTROL_REG(i2c, (I2C_CTL_SI | I2C_CTL_AA));				
			}
			else
			{				
				I2C_SET_CONTROL_REG(i2c, I2C_CTL_SI);
			}
		
			break;
		
		case 0x58:  // DATA has been received and NACK has been returned
			s_MIC_I2CCtrl.pau8Cmd[s_MIC_I2CCtrl.u16Counter++] = I2C_GET_DATA(i2c);
			s_MIC_I2CCtrl.u16ReadSize = 0;	
			I2C_SET_CONTROL_REG(i2c, I2C_CTL_STO_SI);			
			break;	
		}		
    }		
}

void Codec_I2C_Handler(I2C_T* i2c)
{
	if(s_pfn_I2CHandler != NULL)
		s_pfn_I2CHandler(i2c);
}


