typedef struct {
    uint8_t  u8DeviceAddr;
    uint16_t u16Counter;
    uint16_t u16WriteSize;
	uint16_t u16ReadSize;
    uint8_t* pau8Cmd;
} S_MIC_I2CCTRL;

typedef struct {
    uint8_t  u8Reg[2];
    uint8_t  u8Value[2];
} S_MIC_I2CCMD;

volatile S_MIC_I2CCTRL s_MIC_I2CCtrl;     
volatile uint8_t g_u8CodecInit = 0;
volatile uint16_t g_u16CodecTimeOutCnt = 0;
