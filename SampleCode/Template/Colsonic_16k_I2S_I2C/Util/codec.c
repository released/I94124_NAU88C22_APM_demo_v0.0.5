void NAU85L40_Init(I2C_T* i2c)
{
    uint16_t u16i;
    I2C_SetBusClockFreq(i2c,100000);
    s_MIC_I2CCtrl.u8DeviceAddr = 0x1C;

    g_u8CodecInit = 1;
    g_u16CodecTimeOutCnt = 0;
	s_pfn_I2CHandler = I2C_Master_Write_Handler;

    for(u16i=0; u16i<sizeof(asMIC_Cmd_85L40)/sizeof(S_MIC_I2CCMD); u16i++)
    {
        s_MIC_I2CCtrl.pau8Cmd = (uint8_t*)&asMIC_Cmd_85L40[u16i];
        s_MIC_I2CCtrl.u16Counter = 0;
        s_MIC_I2CCtrl.u16WriteSize = sizeof(S_MIC_I2CCMD);
        I2C_START(i2c);
        /* Wait for I2C transmit completed. */
        while((s_MIC_I2CCtrl.u16WriteSize>0) && (g_u16CodecTimeOutCnt < 100)); // 100ms timeout
        if (g_u16CodecTimeOutCnt >= 100)    break;
    }
    g_u8CodecInit = 0;
    g_u16CodecTimeOutCnt = 0;
	s_pfn_I2CHandler = NULL;
}


void NAU85L40_Read(I2C_T* i2c, uint8_t* tmp, uint16_t reg)
{
	S_MIC_I2CCMD cmd;
	
	cmd.u8Reg[0] = (reg>>8)&0xff;
	cmd.u8Reg[1] = reg&0xff;
	
	s_MIC_I2CCtrl.u8DeviceAddr = 0x1C;
	s_MIC_I2CCtrl.pau8Cmd = (uint8_t*)&cmd;
	s_MIC_I2CCtrl.u16Counter = 0;
	s_MIC_I2CCtrl.u16WriteSize = sizeof(cmd.u8Reg);
	s_MIC_I2CCtrl.u16ReadSize = sizeof(cmd.u8Value);
	
	s_pfn_I2CHandler = I2C_Master_Read_Handler;
	I2C_START(i2c);
    /* Wait for I2C transmit completed. */
    while((s_MIC_I2CCtrl.u16ReadSize>0) && (g_u16CodecTimeOutCnt < 100)); // 100ms timeout
	
	memcpy(tmp, s_MIC_I2CCtrl.pau8Cmd, sizeof(cmd.u8Value));
	s_pfn_I2CHandler = NULL;
}

void Set_NAU85L40_Reg(I2C_T* i2c, uint16_t reg, uint16_t val)
{
	S_MIC_I2CCMD cmd;
	s_pfn_I2CHandler = I2C_Master_Write_Handler;
	
	cmd.u8Reg[0] = (reg>>8)&0xff;
	cmd.u8Reg[1] = reg&0xff;
	cmd.u8Value[0] = (val>>8)&0xff;
	cmd.u8Value[1] = val&0xff;
	s_MIC_I2CCtrl.u8DeviceAddr = 0x1C;
	s_MIC_I2CCtrl.pau8Cmd = (uint8_t*)&cmd;
	s_MIC_I2CCtrl.u16Counter = 0;
	s_MIC_I2CCtrl.u16WriteSize = sizeof(S_MIC_I2CCMD);
	I2C_START(i2c);
	while(s_MIC_I2CCtrl.u16WriteSize>0);		
	s_pfn_I2CHandler = NULL;
}

